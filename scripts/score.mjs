#!/usr/bin/env node
// Score the editorial backlog and write content-ops/scorecard.md
// Priority = (Impact x Demand x Confidence) / Effort  (higher = sooner)
import { readFileSync, writeFileSync } from "node:fs";
import yaml from "js-yaml";

const CATEGORY_LABEL = {
  "platform-engineering-idp": "A Platform/IDP",
  "sre-reliability": "B SRE",
  "security-iam": "C Security/IAM",
  "data-mlops": "D Data/MLOps",
  "multicloud-enterprise": "E Multi-Cloud",
  finops: "F FinOps",
  "architecture-leadership": "G Leadership",
};

const CLOUD_LABEL = { aws: "AWS", gcp: "GCP", azure: "Azure", multi: "Multi" };

const doc = yaml.load(readFileSync("content-ops/backlog.yaml", "utf8"));
const topics = doc.topics ?? [];

const planned = topics.filter((t) => (t.status ?? "planned") === "planned");
const published = topics.filter((t) => t.status === "published");
const merged = topics.filter((t) => t.status === "merged");

const scored = planned
  .map((t) => ({
    ...t,
    score: +((t.impact * t.demand * t.confidence) / t.effort).toFixed(2),
  }))
  .sort((a, b) => {
    if (a.requiresOrg !== b.requiresOrg) return a.requiresOrg ? 1 : -1;
    return b.score - a.score;
  });

const band = (t) => {
  if (t.requiresOrg) return "Org-gated";
  const s = t.score;
  return s >= 25 ? "Publish now" : s >= 12 ? "Soon" : s >= 5 ? "Backlog" : "Optional";
};

const fmtDate = (value) => {
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return value ?? "";
};

const lines = [
  "# Backlog Scorecard",
  "",
  "_Generated by `npm run score`. Do not edit by hand._",
  "",
  "Formula: `Priority = (Impact x Demand x Confidence) / Effort`. Org-required topics are pushed last.",
  "",
  `Planned: **${planned.length}** | Published: **${published.length}** | Merged: **${merged.length}**`,
  "",
  "## Planned",
  "",
  "| # | Title | Category | Cloud | Tier | Org | Im | De | Co | Ef | Score | Band |",
  "|---|---|---|---|---|:--:|--:|--:|--:|--:|--:|---|",
  ...scored.map((t) =>
    [
      `| ${t.id}`,
      t.title,
      CATEGORY_LABEL[t.category] ?? t.category,
      CLOUD_LABEL[t.cloud] ?? t.cloud ?? "GCP",
      `T${t.proofTier}`,
      t.requiresOrg ? "yes" : "",
      t.impact,
      t.demand,
      t.confidence,
      t.effort,
      t.score,
      `${band(t)} |`,
    ].join(" | "),
  ),
  "",
  "## Published",
  "",
  "| # | Title | Category | Published as | Date |",
  "|---|---|---|---|---|",
  ...published
    .slice()
    .sort((a, b) => String(fmtDate(a.publishedOn)).localeCompare(String(fmtDate(b.publishedOn))))
    .map(
      (t) =>
        `| ${t.id} | ${t.title} | ${CATEGORY_LABEL[t.category] ?? t.category} | \`${t.publishedAs ?? ""}\` | ${fmtDate(t.publishedOn)} |`,
    ),
  "",
  "## Merged",
  "",
  "| # | Title | Merged into | Note |",
  "|---|---|---|---|",
  ...merged.map((t) => `| ${t.id} | ${t.title} | ${t.mergedInto ?? ""} | ${t.note ?? ""} |`),
  "",
];

writeFileSync("content-ops/scorecard.md", lines.join("\n"));
console.log(
  `Scored ${scored.length} planned topics (${published.length} published, ${merged.length} merged) -> content-ops/scorecard.md`,
);
