#!/usr/bin/env python3
"""Build deterministic Lambda code artifacts for the safe-releases demo.

Each artifact contains:
  handler.py     - the function code
  release.json   - self-describing label and fault mode

The CodeDeploy AppSpec is generated by ``deploy.sh`` at deployment time,
because for Lambda the CodeDeploy revision is the AppSpec, not this code zip.

Usage:
    python scripts/build.py baseline
    python scripts/build.py healthy
    python scripts/build.py faulty

The command prints the absolute path of the built zip.
"""

from __future__ import annotations

import argparse
import json
import shutil
import zipfile
from pathlib import Path

RELEASES: dict[str, tuple[str, str]] = {
    "baseline": ("baseline", "off"),
    "healthy": ("candidate-healthy", "off"),
    "faulty": ("candidate-faulty", "always"),
}


def build(release: str) -> Path:
    label, fail_mode = RELEASES[release]

    root = Path(__file__).resolve().parents[1]
    stage = root / "build" / "stage"
    artifact = root / "build" / f"{release}.zip"

    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)

    shutil.copy2(root / "app" / "handler.py", stage / "handler.py")
    (stage / "release.json").write_text(
        json.dumps({"label": label, "fail_mode": fail_mode}, indent=2) + "\n",
        encoding="utf-8",
    )

    artifact.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(artifact, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in ("handler.py", "release.json"):
            archive.write(stage / name, arcname=name)

    return artifact


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release", choices=sorted(RELEASES))
    args = parser.parse_args()

    print(build(args.release))


if __name__ == "__main__":
    main()
